"""`stimulus scaffold`: start a new HITL experiment from the repo's own pieces, not a blank file.

One command writes (never registers) a TEMP stimulus variant with explicit overrides, a pre-filled
recipe (`docs/Templates/HITL_TEST_RECIPE.md` shape), the gesture helpers and control constants that
actually exist in `scripts/hitl/`, and a marker pre-flight for any marker the test will wait on
(`scripts/check_marker_contract.py`). The goal is to remove the three recurring hardware-iteration
costs: markers that are not Tier-A or never emitted, and key strokes hand-rolled instead of reused.

Nothing here sends MIDI, edits a canonical stimulus, or promotes a variant (AGENTS.md: promote to a
new `STIM-...-02` only when the owner accepts it as the reproducer).
"""

from __future__ import annotations

import ast
import re
from dataclasses import dataclass, replace
from pathlib import Path
from typing import Optional, Sequence

from hitl.stimuli.registry import get_stimulus, temporary_variant
from hitl.stimuli.spec import StimulusSpec
from hitl.stimuli.yaml_view import export_spec_yaml, write_yaml

_HITL_DIR = Path(__file__).resolve().parent.parent
_ACTION_MODULES = ("buttons", "slots", "transport", "observation")
_SUFFIX_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]*$")


@dataclass(frozen=True)
class MarkerResult:
    tag: str
    ok: bool
    message: str


@dataclass(frozen=True)
class ScaffoldResult:
    spec: StimulusSpec
    sidecar: Path
    recipe: Path
    markers: tuple[MarkerResult, ...]

    @property
    def markers_ok(self) -> bool:
        return all(result.ok for result in self.markers)


def gesture_catalogue(actions_dir: Optional[Path] = None) -> list[tuple[str, str, str]]:
    """(module, signature, first doc line) for each public helper in the gesture/observation modules.

    Read with `ast` so the list can never drift from the code and importing it needs no device.
    """
    base = actions_dir or (_HITL_DIR / "actions")
    found: list[tuple[str, str, str]] = []
    for module in _ACTION_MODULES:
        path = base / f"{module}.py"
        if not path.is_file():
            continue
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in tree.body:
            if not isinstance(node, ast.FunctionDef) or node.name.startswith("_"):
                continue
            args = ast.unparse(node.args)
            args = args.replace("action_ctx: ActionContext, ", "").replace("action_ctx: ActionContext", "")
            doc = (ast.get_docstring(node) or "").strip().splitlines()
            found.append((module, f"{node.name}({args})", doc[0] if doc else ""))
    return found


def control_constants(path: Optional[Path] = None) -> list[tuple[str, int]]:
    """Integer control-note/channel constants from `control_constants.py` (names are the contract)."""
    source = (path or (_HITL_DIR / "control_constants.py")).read_text(encoding="utf-8")
    out: list[tuple[str, int]] = []
    for node in ast.parse(source).body:
        if (isinstance(node, ast.Assign) and len(node.targets) == 1
                and isinstance(node.targets[0], ast.Name)
                and isinstance(node.value, ast.Constant) and isinstance(node.value.value, int)):
            name = node.targets[0].id
            if name.endswith(("_NOTE", "_NOTE_BASE")) or name.startswith("CONTROL_CHANNEL"):
                out.append((name, node.value.value))
    return out


def preflight_markers(tags: Sequence[str]) -> tuple[MarkerResult, ...]:
    """The EMITTED / TIER-A / FIT verdict for each declared marker (see check_marker_contract.py)."""
    if not tags:
        return ()
    import check_marker_contract as cmc

    accepted, excluded = cmc.tier_a_prefixes()
    results = []
    for tag in tags:
        ok, message = cmc.check_tag(tag, accepted, excluded)
        results.append(MarkerResult(tag, ok, message))
    return tuple(results)


def render_recipe(spec: StimulusSpec, *, reason: str, results: Sequence[MarkerResult],
                  markers: Sequence[str]) -> str:
    gestures = "\n".join(f"- `{sig}` ({mod}.py){': ' + doc if doc else ''}"
                         for mod, sig, doc in gesture_catalogue())
    constants = ", ".join(f"`{name}`={value}" for name, value in control_constants())
    if results:
        marker_rows = "\n".join(f"| `{r.tag}` | {'OK' if r.ok else 'NOT YET'} | {r.message.split(': ', 1)[-1]} |" for r in results)
    else:
        marker_rows = "| _(none declared)_ | | pass `--marker 'DIAG,my_event,'` to pre-flight |"
    scope = spec.authorization.targets_text() if spec.authorization else "undeclared"
    return f"""# {spec.stimulus_id} (TEMP, not registered)

Generated by `host_midi_hitl.py stimulus scaffold`. Rules: [hitl_authoring_traps.md](../../docs/Agents/hitl_authoring_traps.md).
Never edit the parent `{spec.parent_id}`; promote this variant to a new `STIM-...-02` only when the owner accepts it.

| Field | Value |
|---|---|
| Why the canonical recipe is insufficient | {reason or '_fill in_'} |
| Parent / kind | {spec.parent_id} v{spec.version} / {spec.kind} |
| Acceptance criterion (one sentence) | _fill in_ |
| Authorized targets | {scope} |
| Base | {spec.base_bars} bars, {spec.base_pattern} |
| Must prove | {'; '.join(spec.must_prove) or '_fill in_'} |
| Native test that fails without the change | _suite + case_ |
| Full scenario entry point | _baseline preset or wrapper; managed-run timeout applies_ |

## Markers the test waits on (pre-flight)

`NOT YET` is expected before the firmware row exists; it must be `OK` before flashing.

| Tag | Status | Detail |
|---|---|---|
{marker_rows}

## Reusable gestures (use these; do not hand-roll MIDI bytes)

{gestures}

Constants (`scripts/hitl/control_constants.py`): {constants}

## Order of work

1. Native test (`pio test -e native -f <suite>`), including the tier case for any new marker.
2. `python3 scripts/check_marker_contract.py {' '.join(repr(m) for m in markers) or "'<tag>'"}`, then build `teensy41-capture-serial` and read the RAM1 line.
3. Flash (ask first unless a dedicated HITL preset is evaluating the change), short boot census, confirm the marker.
4. Full scenario via the authoritative entry point; read the log tail or a `scripts/parse_*.py` helper.
"""


def scaffold(parent_id: str, suffix: str, *, out_dir: Path, reason: str = "",
             bars: Optional[int] = None, must_prove: Sequence[str] = (),
             description: Optional[str] = None, markers: Sequence[str] = ()) -> ScaffoldResult:
    """Write the TEMP sidecar and the recipe. Raises KeyError for an unknown parent, ValueError otherwise."""
    if not _SUFFIX_RE.match(suffix):
        raise ValueError(f"suffix {suffix!r} must be letters, digits, '-' or '_'")
    if bars is not None and bars < 1:
        raise ValueError("--bars must be >= 1")
    get_stimulus(parent_id)  # KeyError names the unknown id
    overrides: dict[str, object] = {}
    if bars is not None:
        overrides["base_bars"] = bars
    if must_prove:
        overrides["must_prove"] = tuple(must_prove)
    if description:
        overrides["description"] = description
    spec = temporary_variant(parent_id, suffix, **overrides)
    stimuli_dir = Path(out_dir) / "stimuli"
    sidecar = stimuli_dir / f"{spec.stimulus_id}.yaml"
    text = export_spec_yaml(spec)
    if reason:
        text = f"# reason: {reason}\n" + text
    write_yaml(sidecar, text)
    results = preflight_markers(markers)
    recipe = stimuli_dir / f"{spec.stimulus_id}.recipe.md"
    recipe.write_text(render_recipe(spec, reason=reason, results=results, markers=markers), encoding="utf-8")
    return ScaffoldResult(spec=spec, sidecar=sidecar, recipe=recipe, markers=results)
